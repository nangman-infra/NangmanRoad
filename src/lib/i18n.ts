export function detectLang(): Lang {
  try {
    const stored = globalThis.localStorage?.getItem(LANG_STORAGE_KEY);

    if (stored === "en" || stored === "ko") return stored;
  } catch {
    // No storage: fall through to the browser's language.
  }

  return (globalThis.navigator?.language ?? "").toLowerCase().startsWith("ko") ? "ko" : "en";
}

// The language in force, read by code that runs outside React: the route worker's
// replies are labelled while the visitor is still waiting on the probe.
let currentLang: Lang = "en";

export function setCurrentLang(lang: Lang) {
  currentLang = lang;
}

export function currentLanguage(): Lang {
  return currentLang;
}

export function translate(lang: Lang, key: string, vars: Record<string, string | number> = {}) {
  const template = MESSAGES[lang][key] ?? MESSAGES.en[key] ?? key;

  return template.replace(/\{(\w+)\}/g, (_match, name: string) => (name in vars ? String(vars[name]) : ""));
}

export function t(key: string, vars?: Record<string, string | number>) {
  return translate(currentLang, key, vars);
}

export const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({ lang: "en", setLang: () => {} });

// Subscribes a component to the language, so it re-renders when it changes.
export function useLang() {
  return useContext(LangContext);
}
